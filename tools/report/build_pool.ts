// Build packages/shared/data/pool.json: every real player as a draftable creature.
// Run after `pnpm data:import` / `pnpm data:fit`. `pnpm data:report` validates and prints balance.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { PoolFileSchema } from "@tdf/shared";
import { buildPool, poolHash } from "@tdf/sim";
import { nodeGameData, SHARED } from "./node-data.js";

export async function main() {
  const data = await nodeGameData();
  const creatures = buildPool(data);
  const file = PoolFileSchema.parse({
    _doc: "Generated by tools/report/build_pool.ts from players.json + config. Do not edit by hand.",
    source: data.players.source,
    hash: poolHash(creatures),
    creatures,
  });
  writeFileSync(join(SHARED, "data", "pool.json"), JSON.stringify(file) + "\n");
  console.log(`pool.json: ${creatures.length} creatures, hash ${file.hash}`);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
